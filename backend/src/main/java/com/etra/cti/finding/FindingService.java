@Service
public class FindingService {

    private static final Logger log = LoggerFactory.getLogger(FindingService.class);

    private final FindingRepository findings;
    private final ApplicationRepository apps;
    private final com.etra.cti.project.ProjectRepository projects;
    private final com.etra.cti.organization.OrganizationService orgService;
    private final RiskEngine riskEngine;
    private final AuditService audit;
    private final RemediationRepository remediations;
    private final RemediationAdvisor advisor;

    public FindingService(FindingRepository findings,
                          ApplicationRepository apps,
                          com.etra.cti.project.ProjectRepository projects,
                          com.etra.cti.organization.OrganizationService orgService,
                          RiskEngine riskEngine,
                          AuditService audit,
                          RemediationRepository remediations,
                          RemediationAdvisor advisor) {
        this.findings = findings;
        this.apps = apps;
        this.projects = projects;
        this.orgService = orgService;
        this.riskEngine = riskEngine;
        this.audit = audit;
        this.remediations = remediations;
        this.advisor = advisor;
    }

    @Transactional
    public FindingDto create(CreateFindingRequest req, UUID createdBy) {
        Application app = apps.findById(req.applicationId())
            .orElseThrow(() -> new NotFoundException("Application not found"));

        if (createdBy != null) {
            com.etra.cti.project.Project project = projects.findById(app.getProjectId())
                .orElseThrow(() -> new NotFoundException("Project not found"));
            orgService.requireMember(project.getOrganizationId(), createdBy);
        }

        Finding f = new Finding();
        f.setReference(nextReference());
        f.setApplicationId(app.getId());
        f.setDetectionId(req.detectionId());
        f.setTitle(req.title());
        f.setDescription(req.description());
        f.setEndpoint(req.endpoint());
        f.setParameter(req.parameter());
        f.setSeverity(req.severity());
        f.setConfidence(req.confidence());
        f.setSource(req.source());
        f.setSourceDisplay(displayNameFor(req.source()));
        f.setStatus(FindingStatus.OPEN);
        f.setCreatedBy(createdBy);

        var risk = riskEngine.calculate(req.severity(), req.confidence(), app, 1.0);
        f.setRiskScore(risk.score());
        f.setRiskBand(risk.band());
        findings.saveAndFlush(f);

        // ===== AUTO-GENERATE REMEDIATION for HIGH/CRITICAL =====
        if (req.severity() == com.etra.cti.detection.Severity.HIGH
            || req.severity() == com.etra.cti.detection.Severity.CRITICAL) {
            autoCreateRemediation(f);
        }

        audit.record(createdBy, "FINDING_CREATED", "Finding", f.getId().toString(),
            Map.of("reference", f.getReference(),
                   "severity", f.getSeverity().name(),
                   "riskScore", f.getRiskScore(),
                   "riskBand", f.getRiskBand(),
                   "source", String.valueOf(f.getSource())));

        return FindingDto.from(f);
    }

    /**
     * Public so IntegrationService and MobileAppService can also auto-create remediations.
     */
    @Transactional
    public void autoCreateRemediation(Finding f) {
        if (remediations.findByFindingId(f.getId()).isPresent()) {
            return;
        }
        var advice = advisor.advise(f.getTitle(), f.getDescription());

        Remediation r = new Remediation();
        r.setFindingId(f.getId());
        r.setStatus(RemediationStatus.OPEN);
        r.setAutoGenerated(true);
        r.setRecommendation(advice.recommendation());
        r.setRecommendationSource(advice.title() + " (CWE: " + advice.cwe() + ", " + advice.owasp() + ")");
        r.setStartedAt(Instant.now());
        remediations.save(r);

        log.info(">>> Auto-generated remediation for {}: {}",
            f.getReference(), advice.title());
    }

    private String displayNameFor(String source) {
        if (source == null) return "Unknown";
        return switch (source.toUpperCase()) {
            case "BURP"            -> "Burp Suite";
            case "ZAP"             -> "OWASP ZAP";
            case "NMAP"            -> "Nmap";
            case "MOBSF"           -> "MobSF (Mobile Security Framework)";
            case "APPLICATION_LOG" -> "Application Log";
            case "API_GATEWAY"     -> "API Gateway";
            case "MANUAL"          -> "Manual Entry";
            default                -> source;
        };
    }

    public Page<FindingDto> list(Pageable pageable) {
        return list(null, null, null, null, null, pageable, null);
    }

    public Page<FindingDto> list(UUID applicationId,
                                 FindingStatus status,
                                 Severity severity,
                                 UUID assignedTo,
                                 Boolean overdue,
                                 Pageable pageable) {
        return list(applicationId, status, severity, assignedTo, overdue, pageable, null);
    }

    public Page<FindingDto> list(UUID applicationId,
                                 FindingStatus status,
                                 Severity severity,
                                 UUID assignedTo,
                                 Boolean overdue,
                                 Pageable pageable,
                                 com.etra.cti.auth.JwtAuthFilter.AuthedUser caller) {
        List<UUID> allowedAppIds = null;
        if (caller != null && !"ADMIN".equalsIgnoreCase(caller.role()) && !orgService.isPlatformStaff(caller.id())) {
            List<UUID> orgIds = orgService.listMine(caller.id()).stream()
                .map(com.etra.cti.organization.dto.OrganizationDto::id)
                .toList();
            if (orgIds.isEmpty()) {
                if (applicationId != null) {
                    throw new org.springframework.security.access.AccessDeniedException("Not authorized for application " + applicationId);
                }
                return Page.empty(pageable);
            }
            allowedAppIds = orgIds.stream()
                .flatMap(orgId -> projects.findByOrganizationId(orgId).stream())
                .flatMap(project -> apps.findByProjectId(project.getId()).stream())
                .map(Application::getId)
                .distinct()
                .toList();
            if (allowedAppIds.isEmpty()) {
                if (applicationId != null) {
                    throw new org.springframework.security.access.AccessDeniedException("Not authorized for application " + applicationId);
                }
                return Page.empty(pageable);
            }
            if (applicationId != null && !allowedAppIds.contains(applicationId)) {
                throw new org.springframework.security.access.AccessDeniedException("Not authorized for application " + applicationId);
            }
        }

        final List<UUID> scopedAppIds = allowedAppIds;
        Specification<Finding> spec = (root, query, cb) -> {
            List<Predicate> predicates = new ArrayList<>();
            if (applicationId != null) {
                predicates.add(cb.equal(root.get("applicationId"), applicationId));
            } else if (scopedAppIds != null) {
                predicates.add(root.get("applicationId").in(scopedAppIds));
            }
            if (status != null) {
                predicates.add(cb.equal(root.get("status"), status));
            }
            if (severity != null) {
                predicates.add(cb.equal(root.get("severity"), severity));
            }
            if (assignedTo != null) {
                predicates.add(cb.equal(root.get("assignedTo"), assignedTo));
            }
            if (Boolean.TRUE.equals(overdue)) {
                predicates.add(cb.isNotNull(root.get("dueDate")));
                predicates.add(cb.lessThan(root.get("dueDate"), Instant.now()));
                predicates.add(cb.not(root.get("status").in(FindingStatus.VERIFIED, FindingStatus.CLOSED)));
            }
            return cb.and(predicates.toArray(new Predicate[0]));
        };
        return findings.findAll(spec, pageable).map(FindingDto::from);
    }

    public Page<FindingDto> listByApplication(UUID appId, Pageable pageable) {
        return findings.findByApplicationIdOrderByRiskScoreDesc(appId, pageable).map(FindingDto::from);
    }

    public FindingDto get(UUID id, com.etra.cti.auth.JwtAuthFilter.AuthedUser caller) {
        Finding f = findings.findById(id).orElseThrow(() -> new NotFoundException("Finding not found"));
        if (caller != null && !"ADMIN".equalsIgnoreCase(caller.role())) {
            Application app = apps.findById(f.getApplicationId()).orElseThrow(() -> new NotFoundException("Application not found"));
            com.etra.cti.project.Project project = projects.findById(app.getProjectId()).orElseThrow(() -> new NotFoundException("Project not found"));
            orgService.requireMember(project.getOrganizationId(), caller.id());
        }
        return FindingDto.from(f);
    }

    public FindingDto get(UUID id) {
        return get(id, null);
    }

    private void validateAccess(Finding f, UUID userId) {
        if (userId == null) return;
        Application app = apps.findById(f.getApplicationId())
            .orElseThrow(() -> new NotFoundException("Application not found"));
        com.etra.cti.project.Project project = projects.findById(app.getProjectId())
            .orElseThrow(() -> new NotFoundException("Project not found"));
        orgService.requireMember(project.getOrganizationId(), userId);
    }

    @Transactional
    public FindingDto updateStatus(UUID id, FindingStatus status, UUID userId) {
        Finding f = findings.findById(id).orElseThrow(() -> new NotFoundException("Finding not found"));
        validateAccess(f, userId);
        FindingStatus old = f.getStatus();
        f.setStatus(status);
        findings.save(f);
        audit.recordChange(userId, "FINDING_STATUS_CHANGED", "Finding", id.toString(),
            Map.of("status", old.name()),
            Map.of("status", status.name()));
        return FindingDto.from(f);
    }

    @Transactional
    public FindingDto updateStatus(UUID id, FindingStatus status) {
        return updateStatus(id, status, null);
    }

    @Transactional
    public FindingDto assign(UUID id, UUID assignedTo) {
        return assign(id, assignedTo, null, null);
    }

    @Transactional
    public FindingDto assign(UUID id, UUID assignedTo, Instant dueDate, UUID actorId) {
        Finding f = findings.findById(id).orElseThrow(() -> new NotFoundException("Finding not found"));
        validateAccess(f, actorId);
        UUID oldAssignee = f.getAssignedTo();
        Instant oldDue = f.getDueDate();
        f.setAssignedTo(assignedTo);
        if (dueDate != null) {
            f.setDueDate(dueDate);
        }
        if (f.getStatus() == FindingStatus.OPEN) {
            f.setStatus(FindingStatus.ASSIGNED);
        }
        findings.save(f);
        audit.recordChange(actorId, "FINDING_ASSIGNED", "Finding", id.toString(),
            oldAssignee == null ? Map.of() : Map.of("assignedTo", oldAssignee, "dueDate", oldDue == null ? "none" : oldDue.toString()),
            Map.of("assignedTo", assignedTo, "dueDate", f.getDueDate() == null ? "none" : f.getDueDate().toString()));
        return FindingDto.from(f);
    }

    @Transactional
    public FindingDto setDueDate(UUID id, Instant dueDate, UUID actorId) {
        Finding f = findings.findById(id).orElseThrow(() -> new NotFoundException("Finding not found"));
        validateAccess(f, actorId);
        Instant oldDue = f.getDueDate();
        f.setDueDate(dueDate);
        findings.save(f);
        audit.recordChange(actorId, "FINDING_DUE_DATE_UPDATED", "Finding", id.toString(),
            Map.of("dueDate", oldDue == null ? "none" : oldDue.toString()),
            Map.of("dueDate", dueDate == null ? "none" : dueDate.toString()));
        return FindingDto.from(f);
    }

    @Transactional
    public FindingDto overridePriority(UUID id, OverridePriorityRequest req, UUID actorId) {
        Finding f = findings.findById(id).orElseThrow(() -> new NotFoundException("Finding not found"));
        validateAccess(f, actorId);
        Severity oldSev = f.getSeverity();
        BigDecimal oldScore = f.getRiskScore();

        f.setSeverity(req.severity());
        f.setPriorityOverrideReason(req.reason());

        Application app = apps.findById(f.getApplicationId()).orElse(null);
        var risk = riskEngine.calculate(req.severity(), f.getConfidence(), app, 1.0);
        f.setRiskScore(risk.score());
        f.setRiskBand(risk.band());
        findings.save(f);

        audit.recordChange(actorId, "FINDING_PRIORITY_OVERRIDDEN", "Finding", id.toString(),
            Map.of("severity", oldSev.name(), "riskScore", oldScore != null ? oldScore : 0),
            Map.of("severity", req.severity().name(), "riskScore", risk.score(), "reason", req.reason()));

        log.info(">>> Finding {} priority overridden to {} by manager {}: {}",
            f.getReference(), req.severity(), actorId, req.reason());
        return FindingDto.from(f);
    }

    public synchronized String nextReference() {
        long n = findings.count() + 1;
        String ref = String.format("ETRA-%05d", n);
        while (findings.existsByReference(ref)) {
            n++;
            ref = String.format("ETRA-%05d", n);
        }
        return ref;
    }
}
