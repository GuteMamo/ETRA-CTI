package com.etra.cti.remediation;

import com.etra.cti.common.BaseEntity;
import jakarta.persistence.*;

import java.time.Instant;
import java.util.UUID;

@Entity
@Table(name = "remediations")
public class Remediation extends BaseEntity {

    @Column(name = "finding_id", nullable = false, unique = true)
    private UUID findingId;

    @Column(name = "developer_id")
    private UUID developerId;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 30)
    private RemediationStatus status = RemediationStatus.OPEN;

    @Column(name = "fix_notes", columnDefinition = "TEXT")
    private String fixNotes;

    @Column(name = "commit_ref", length = 255)
    private String commitRef;

    @Column(name = "started_at")
    private Instant startedAt;

    @Column(name = "fixed_at")
    private Instant fixedAt;

    @Column(name = "verified_at")
    private Instant verifiedAt;

    @Column(name = "reopened_count", nullable = false)
    private Integer reopenedCount = 0;

    @Column(name = "auto_generated", nullable = false)
    private Boolean autoGenerated = false;

    @Column(columnDefinition = "TEXT")
    private String recommendation;

    @Column(name = "recommendation_source", length = 100)
    private String recommendationSource;

    public UUID getFindingId() { return findingId; }
    public void setFindingId(UUID findingId) { this.findingId = findingId; }

    public UUID getDeveloperId() { return developerId; }
    public void setDeveloperId(UUID developerId) { this.developerId = developerId; }

    public RemediationStatus getStatus() { return status; }
    public void setStatus(RemediationStatus status) { this.status = status; }

    public String getFixNotes() { return fixNotes; }
    public void setFixNotes(String fixNotes) { this.fixNotes = fixNotes; }

    public String getCommitRef() { return commitRef; }
    public void setCommitRef(String commitRef) { this.commitRef = commitRef; }

    public Instant getStartedAt() { return startedAt; }
    public void setStartedAt(Instant startedAt) { this.startedAt = startedAt; }

    public Instant getFixedAt() { return fixedAt; }
    public void setFixedAt(Instant fixedAt) { this.fixedAt = fixedAt; }

    public Instant getVerifiedAt() { return verifiedAt; }
    public void setVerifiedAt(Instant verifiedAt) { this.verifiedAt = verifiedAt; }

    public Integer getReopenedCount() { return reopenedCount; }
    public void setReopenedCount(Integer reopenedCount) { this.reopenedCount = reopenedCount; }

    public Boolean getAutoGenerated() { return autoGenerated; }
    public void setAutoGenerated(Boolean autoGenerated) { this.autoGenerated = autoGenerated; }

    public String getRecommendation() { return recommendation; }
    public void setRecommendation(String recommendation) { this.recommendation = recommendation; }

    public String getRecommendationSource() { return recommendationSource; }
    public void setRecommendationSource(String recommendationSource) { this.recommendationSource = recommendationSource; }
}
